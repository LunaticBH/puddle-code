/**
 * Windows session-shell hooks (SPEC §4, docs/windows.md decision 7), written
 * at boot beside the POSIX ones only when the daemon runs on Windows.
 *
 * PowerShell (5.1 and 7) receives the same private OSC 7733 reports as bash
 * and zsh: the prompt directory and, when the profile enables it, exported
 * environment changes. Its history is isolated through PSReadLine's
 * HistorySavePath. The hook is dot-sourced by
 * `-NoExit -Command ". ([ScriptBlock]::Create([IO.File]::ReadAllText('<hook>')))"`,
 * which runs after the user's profile and which execution policy does not
 * block. Under ConstrainedLanguage mode (WDAC) the method calls are refused
 * and the shell starts without hooks.
 *
 * Git Bash reuses the bash rcfile and only replaces its directory report,
 * because MSYS spells `C:\x` as `/c/x` and maps `/` and `/tmp` to Windows
 * directories only it knows: `pwd -W` gives the native path.
 */

// The agent hooks' quoting: a home path may hold a typographic quote
// (C:\Users\O’Brien), which also closes a PowerShell literal.
import { powershellLiteral } from '../agents/shell-quote.js';

/** A POSIX shell single-quoted word. */
function shellWord(value: string): string {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

/** The `-Command` text that dot-sources the PowerShell hook file. */
export function powershellHookCommand(hookFile: string): string {
  return `. ([ScriptBlock]::Create([IO.File]::ReadAllText(${powershellLiteral(hookFile)})))`;
}

export interface PowershellHookOptions {
  /** Upper-case names never captured. */
  denylist: Iterable<string>;
  /** Upper-case prefixes never captured. */
  deniedPrefixes: readonly string[];
  /** Raw values above this many characters are skipped; the daemon re-checks bytes. */
  maxValueChars: number;
}

export const powershellHook = (opts: PowershellHookOptions) =>
  `# Generated by puddle at daemon boot — do not edit (session-shell hook, SPEC §4).
# Dot-sourced after the user's profile. Save the private controls, then keep
# the user's prompt, $? and $LASTEXITCODE exactly as they would be.
$global:__puddle_capture_env = $env:PUDDLE_CAPTURE_ENV -ne '0'
$global:__puddle_history_file = [string]$env:PUDDLE_HISTFILE
Remove-Item -LiteralPath Env:PUDDLE_CAPTURE_ENV, Env:PUDDLE_HISTFILE -ErrorAction SilentlyContinue

# PSReadLine reads its history file on the first prompt, so pointing it here
# keeps the session's history apart from the user's own.
function global:__puddle_claim_history {
  if (-not $global:__puddle_history_file) { return }
  if (-not (Get-Command Set-PSReadLineOption -ErrorAction SilentlyContinue)) { return }
  if ((Get-PSReadLineOption).HistorySavePath -cne $global:__puddle_history_file) {
    Set-PSReadLineOption -HistorySavePath $global:__puddle_history_file
  }
}
__puddle_claim_history

$global:__puddle_denied = @{}
foreach ($__puddle_name in @(${[...opts.denylist].map(powershellLiteral).join(', ')})) {
  $global:__puddle_denied[$__puddle_name] = $true
}
Remove-Variable -Name __puddle_name -ErrorAction SilentlyContinue
$global:__puddle_denied_prefixes = @(${opts.deniedPrefixes.map((prefix) => powershellLiteral(`${prefix}*`)).join(', ')})
$global:__puddle_last_cwd = $null
$global:__puddle_env_last = @{}

function global:__puddle_b64([string] $text) {
  [Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes($text))
}

function global:__puddle_osc([string] $payload) {
  "$([char]27)]7733;$payload$([char]7)"
}

function global:__puddle_cwd_report {
  $location = $ExecutionContext.SessionState.Path.CurrentLocation
  if ($location.Provider.Name -ne 'FileSystem') { return '' }
  $path = $location.ProviderPath
  if ($path -ceq $global:__puddle_last_cwd) { return '' }
  $global:__puddle_last_cwd = $path
  __puddle_osc "cwd;$(__puddle_b64 $path)"
}

function global:__puddle_env_scan {
  $now = @{}
  foreach ($entry in [Environment]::GetEnvironmentVariables().GetEnumerator()) {
    $name = [string]$entry.Key
    if ($name -cnotmatch '^[A-Za-z_][A-Za-z0-9_]*$') { continue }
    if ($global:__puddle_denied.ContainsKey($name.ToUpperInvariant())) { continue }
    $prefixed = $false
    foreach ($prefix in $global:__puddle_denied_prefixes) { if ($name -like $prefix) { $prefixed = $true } }
    if ($prefixed) { continue }
    $value = [string]$entry.Value
    if ($value.Length -gt ${opts.maxValueChars}) { continue }
    $now[$name] = $value
  }
  return $now
}

function global:__puddle_env_report {
  $now = __puddle_env_scan
  $report = New-Object System.Text.StringBuilder
  foreach ($name in $now.Keys) {
    if (-not $global:__puddle_env_last.ContainsKey($name) -or $global:__puddle_env_last[$name] -cne $now[$name]) {
      [void]$report.Append((__puddle_osc "set;$(__puddle_b64 $name);$(__puddle_b64 $now[$name])"))
    }
  }
  foreach ($name in $global:__puddle_env_last.Keys) {
    if (-not $now.ContainsKey($name)) {
      [void]$report.Append((__puddle_osc "unset;$(__puddle_b64 $name)"))
    }
  }
  $global:__puddle_env_last = $now
  $report.ToString()
}

# Seed after the profile ran: profile exports and re-injected captured vars
# are baseline, not deltas, so a respawn never feeds back.
if ($global:__puddle_capture_env) { $global:__puddle_env_last = __puddle_env_scan }

$global:__puddle_user_prompt = $function:prompt
function global:prompt {
  $failed = -not $global:?
  $exitCode = $global:LASTEXITCODE
  try {
    __puddle_claim_history
    $report = [string](__puddle_cwd_report)
    if ($global:__puddle_capture_env) { $report += [string](__puddle_env_report) }
    if ($report) { [Console]::Write($report) }
  } catch {
    # Reporting must never break the prompt.
  }
  $global:LASTEXITCODE = $exitCode
  # Put $? back for prompts that show the last command's outcome.
  if ($failed) { Write-Error -Message 'puddle' -ErrorAction Ignore }
  & $global:__puddle_user_prompt
}
`;

/** Git Bash's rcfile: the bash hook with a native-path directory report. */
export const gitBashRcfile = (bashRc: string) =>
  `# Generated by puddle at daemon boot — do not edit (session-shell hook, SPEC §4).
# Spawned as: bash.exe --rcfile <this file> by a daemon on Windows.
. ${shellWord(bashRc)}
if declare -F _puddle_env_b64 >/dev/null; then
  _puddle_cwd_report() {
    if [ "$_puddle_last_cwd" != "$PWD" ]; then
      printf '\\033]7733;cwd;%s\\007' "$(_puddle_env_b64 "$(builtin pwd -W 2>/dev/null || printf %s "$PWD")")"
      _puddle_last_cwd=$PWD
    fi
  }
fi
`;
