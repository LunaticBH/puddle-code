import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { PuddlePaths } from '../paths.js';
import { shellKind, type ShellKind } from './shell.js';
import { gitBashRcfile, powershellHook, powershellHookCommand } from './windows-shell-hooks.js';

/**
 * Session-shell hooks (SPEC §4). At each prompt they report cwd and, when the
 * profile enables it, exported-environment changes over the private OSC 7733
 * side-channel (see env-osc.ts). They also isolate command history in the
 * Puddle session after the user's rc has loaded, then flush it each prompt.
 *
 * zsh is hooked via a ZDOTDIR shim directory whose zdot files chain to the
 * user's real ones; bash via --rcfile. Both restore the user's view of the
 * world once loaded, so `exec zsh`, nested shells, and child processes never
 * see the shim. Bash < 4 (macOS /bin/bash 3.2) degrades gracefully for env
 * capture; cwd and history still work. Unrecognised shells receive the private
 * HISTFILE but no prompt hook.
 *
 * Hook sources are embedded strings written at boot (the claude-statusline.ts
 * precedent): the daemon builds with plain tsc and ships no static assets.
 */

/**
 * Names never captured: per-shell/terminal state, prompt machinery, and
 * identity vars whose capture would corrupt future spawns rather than help
 * them. The PUDDLE_ prefix is denied as a rule (hook control vars). Kept in
 * sync with the shell templates below, which interpolate SHELL_DENYLIST;
 * SessionService re-checks daemon-side via isDeniedEnvName (defence in depth).
 */
export const ENV_CAPTURE_DENYLIST: ReadonlySet<string> = new Set([
  'PWD',
  'OLDPWD',
  'HISTFILE',
  'SHLVL',
  '_',
  'PS1',
  'PS2',
  'PROMPT',
  'PROMPT_COMMAND',
  'TERM',
  'TERMINFO',
  'COLUMNS',
  'LINES',
  'ZDOTDIR',
  'HOME',
  'SHELL',
  'USER',
  'LOGNAME',
  'TERM_PROGRAM',
  'TERM_PROGRAM_VERSION',
  'TERM_SESSION_ID',
]);

/**
 * The Windows counterpart, kept separate so the POSIX templates never change
 * (docs/windows.md, decision 1). Names are upper case and compared case
 * insensitively, as Windows compares them: the POSIX names (still set by Git
 * Bash and MSYS tools), the Windows identity and per-logon variables, the
 * terminal host's, PowerShell's own, and MSYS's.
 */
export const WINDOWS_ENV_CAPTURE_DENYLIST: ReadonlySet<string> = new Set([
  ...ENV_CAPTURE_DENYLIST,
  'USERNAME',
  'USERPROFILE',
  'USERDOMAIN',
  'USERDOMAIN_ROAMINGPROFILE',
  'HOMEDRIVE',
  'HOMEPATH',
  'HOMESHARE',
  'APPDATA',
  'LOCALAPPDATA',
  'COMPUTERNAME',
  'LOGONSERVER',
  'SESSIONNAME',
  'CLIENTNAME',
  'PSMODULEPATH',
  'PSEXECUTIONPOLICYPREFERENCE',
  'POWERSHELL_DISTRIBUTION_CHANNEL',
  'MSYSTEM',
  'MSYS',
  'ORIGINAL_PATH',
  'ORIGINAL_TEMP',
  'ORIGINAL_TMP',
  'EXEPATH',
  'PLINK_PROTOCOL',
  'HOSTNAME',
]);

/** Windows name prefixes denied as a rule, PUDDLE_ (hook control) included. */
export const WINDOWS_ENV_CAPTURE_DENIED_PREFIXES: readonly string[] = [
  'PUDDLE_',
  'WT_',
  'MSYSTEM_',
  'MINGW_',
  'MSYS2_',
];

export function isDeniedEnvName(
  name: string,
  platform: NodeJS.Platform = process.platform,
): boolean {
  if (platform !== 'win32') return name.startsWith('PUDDLE_') || ENV_CAPTURE_DENYLIST.has(name);
  const upper = name.toUpperCase();
  return (
    WINDOWS_ENV_CAPTURE_DENYLIST.has(upper) ||
    WINDOWS_ENV_CAPTURE_DENIED_PREFIXES.some((prefix) => upper.startsWith(prefix))
  );
}

const SHELL_DENYLIST = [...ENV_CAPTURE_DENYLIST].join(' ');

/** Raw values above this are skipped shell-side; the daemon re-enforces by byte (SPEC §4). */
const MAX_VALUE_CHARS = 32 * 1024;

/* eslint-disable no-useless-escape -- the templates below are shell, not JS */

const zshEnvReport =
  () => `# Generated by puddle at daemon boot — do not edit (session-shell hook, SPEC §4).
# History was isolated before the user's rc initialised ZLE, environment
# managers, and prompt frameworks. Keep the private path authoritative without
# replacing that live history context after those integrations have loaded.
[[ -n \${_puddle_session_history_file-} ]] && HISTFILE=\$_puddle_session_history_file

autoload -Uz add-zsh-hook 2>/dev/null || return 0
command -v base64 >/dev/null 2>&1 || return 0

typeset -g _puddle_last_cwd=''
_puddle_env_b64() { printf %s "\$1" | command base64 | command tr -d '\\n'; }

_puddle_cwd_report() {
  if [[ \$_puddle_last_cwd != "\$PWD" ]]; then
    printf '\\033]7733;cwd;%s\\007' "\$(_puddle_env_b64 "\$PWD")"
    _puddle_last_cwd=\$PWD
  fi
}

typeset -ga _puddle_env_denied
_puddle_env_denied=( ${SHELL_DENYLIST} )
typeset -gA _puddle_env_last _puddle_env_now

_puddle_env_scan() {
  _puddle_env_now=()
  local k t
  for k in \${(k)parameters}; do
    t=\$parameters[\$k]
    [[ \$t == *export* ]] || continue
    [[ \$t == *array* || \$t == *association* ]] && continue
    [[ \$k == PUDDLE_* ]] && continue
    (( \${_puddle_env_denied[(Ie)\$k]} )) && continue
    (( \${#\${(P)k}} > ${MAX_VALUE_CHARS} )) && continue
    _puddle_env_now[\$k]=\${(P)k}
  done
}

_puddle_env_report() {
  _puddle_env_scan
  local k
  for k in \${(k)_puddle_env_now}; do
    if (( ! \${+_puddle_env_last[\$k]} )) || [[ \${_puddle_env_last[\$k]} != \${_puddle_env_now[\$k]} ]]; then
      printf '\\033]7733;set;%s;%s\\007' "\$(_puddle_env_b64 "\$k")" "\$(_puddle_env_b64 "\${_puddle_env_now[\$k]}")"
    fi
  done
  for k in \${(k)_puddle_env_last}; do
    if (( ! \${+_puddle_env_now[\$k]} )); then
      printf '\\033]7733;unset;%s\\007' "\$(_puddle_env_b64 "\$k")"
    fi
  done
  _puddle_env_last=("\${(@kv)_puddle_env_now}")
}

_puddle_prompt_report() {
  if [[ -n \${_puddle_session_history_file-} ]]; then
    # Prompt/directory/environment hooks may repoint HISTFILE after startup.
    # Reclaim it before the next command: incremental history modes otherwise
    # mark entries as written to that foreign file before fc -AI can save them
    # in the Puddle session.
    HISTFILE=\$_puddle_session_history_file
    builtin fc -AI "\$_puddle_session_history_file" 2>/dev/null
  fi
  _puddle_cwd_report
  (( \${_puddle_capture_env_requested:-1} )) && _puddle_env_report
}

if (( \${_puddle_capture_env_requested:-1} )); then
  if zmodload -i zsh/parameter 2>/dev/null; then
    # Seed the baseline AFTER the user's rc ran: rc-set exports (and re-injected
    # captured vars) are baseline, not deltas — no feedback loop on respawn.
    _puddle_env_scan
    _puddle_env_last=("\${(@kv)_puddle_env_now}")
  else
    typeset -g _puddle_capture_env_requested=0
  fi
fi
add-zsh-hook precmd _puddle_prompt_report
`;

const zshZshenv = (
  zshDir: string,
) => `# Generated by puddle at daemon boot — do not edit (captured-env hook, SPEC §4).
# Puddle spawned this shell with ZDOTDIR pointed here; hand the user their real
# environment back, remembering what they had so .zshrc can restore it exactly.
typeset -g _puddle_capture_env_requested=\${PUDDLE_CAPTURE_ENV:-1}
typeset -g _puddle_session_history_file=\${PUDDLE_HISTFILE-}
unset PUDDLE_CAPTURE_ENV PUDDLE_HISTFILE
if [[ -n \${PUDDLE_ORIG_ZDOTDIR-} ]]; then
  ZDOTDIR=\$PUDDLE_ORIG_ZDOTDIR
else
  unset ZDOTDIR
fi
unset PUDDLE_ORIG_ZDOTDIR
[[ -f "\${ZDOTDIR:-\$HOME}/.zshenv" ]] && builtin source "\${ZDOTDIR:-\$HOME}/.zshenv"
# Establish the final history context before the rest of the user's startup
# files initialise ZLE widgets, environment managers, or prompt frameworks.
# Replacing it after .zshrc breaks integrations that retain history state.
if [[ -n \${_puddle_session_history_file-} ]]; then
  HISTFILE=\$_puddle_session_history_file
  (( HISTSIZE > 0 )) || HISTSIZE=10000
  (( SAVEHIST > 0 )) || SAVEHIST=10000
  setopt APPEND_HISTORY
  builtin fc -p "\$HISTFILE"
fi
# The user's .zshenv may itself repoint ZDOTDIR — honour that as their choice.
typeset -g _puddle_user_had_zdotdir=\${+ZDOTDIR}
typeset -g _puddle_user_zdotdir=\${ZDOTDIR-}
ZDOTDIR=${JSON.stringify(zshDir)}
`;

const zshZprofile = (
  zshDir: string,
) => `# Generated by puddle at daemon boot — do not edit (captured-env hook, SPEC §4).
if (( _puddle_user_had_zdotdir )); then ZDOTDIR=\$_puddle_user_zdotdir; else unset ZDOTDIR; fi
[[ -f "\${ZDOTDIR:-\$HOME}/.zprofile" ]] && builtin source "\${ZDOTDIR:-\$HOME}/.zprofile"
typeset -g _puddle_user_had_zdotdir=\${+ZDOTDIR}
typeset -g _puddle_user_zdotdir=\${ZDOTDIR-}
ZDOTDIR=${JSON.stringify(zshDir)}
`;

const zshZshrc = (
  zshDir: string,
) => `# Generated by puddle at daemon boot — do not edit (captured-env hook, SPEC §4).
if (( _puddle_user_had_zdotdir )); then ZDOTDIR=\$_puddle_user_zdotdir; else unset ZDOTDIR; fi
[[ -f "\${ZDOTDIR:-\$HOME}/.zshrc" ]] && builtin source "\${ZDOTDIR:-\$HOME}/.zshrc"
# ZDOTDIR now holds the user's value (or their rc's choice) permanently —
# exec'd shells, nested zsh, and children must never see the puddle shim.
builtin source ${JSON.stringify(join(zshDir, 'env-report.zsh'))}
unset _puddle_user_had_zdotdir _puddle_user_zdotdir
`;

const zshZlogin = (
  zshDir: string,
) => `# Generated by puddle at daemon boot — do not edit (captured-env hook, SPEC §4).
# .zshrc restores the user's ZDOTDIR before zsh reads .zlogin, so this file is
# normally unreachable; the guard prevents self-sourcing if it ever is.
[[ -f "\${ZDOTDIR:-\$HOME}/.zlogin" && "\${ZDOTDIR:-\$HOME}" != ${JSON.stringify(zshDir)} ]] && builtin source "\${ZDOTDIR:-\$HOME}/.zlogin"
`;

const bashRcfile =
  () => `# Generated by puddle at daemon boot — do not edit (session-shell hook, SPEC §4).
# Spawned as: bash --rcfile <this file>. Save private controls, then restore
# normal user startup behaviour.
_puddle_capture_env_requested=\${PUDDLE_CAPTURE_ENV:-1}
_puddle_session_history_file=\${PUDDLE_HISTFILE-}
unset PUDDLE_CAPTURE_ENV PUDDLE_HISTFILE
# Establish the final history list before the user's rc initialises Readline,
# environment managers, or prompt frameworks. Replacing it afterwards breaks
# integrations that retain history state or install history-search bindings.
if [ -n "\$_puddle_session_history_file" ]; then
  HISTFILE=\$_puddle_session_history_file
  shopt -s histappend
  history -c
  history -r "\$HISTFILE" 2>/dev/null || true
fi
[ -f "\$HOME/.bashrc" ] && . "\$HOME/.bashrc"
# A user rc may reassign HISTFILE; storage remains session-private, but its
# in-memory history and line-editor setup stay intact.
[ -n "\$_puddle_session_history_file" ] && HISTFILE=\$_puddle_session_history_file

_puddle_env_report() { :; }
_puddle_cwd_report() { :; }

if command -v base64 >/dev/null 2>&1; then
  _puddle_env_b64() { printf %s "\$1" | command base64 | command tr -d '\\n'; }
  _puddle_last_cwd=
  _puddle_cwd_report() {
    if [ "\$_puddle_last_cwd" != "\$PWD" ]; then
      printf '\\033]7733;cwd;%s\\007' "\$(_puddle_env_b64 "\$PWD")"
      _puddle_last_cwd=\$PWD
    fi
  }
fi

# Captured env needs associative arrays (bash >= 4); cwd/history do not.
if [ "\$_puddle_capture_env_requested" != 0 ] && [ -n "\${BASH_VERSINFO-}" ] && [ "\${BASH_VERSINFO[0]}" -ge 4 ] && command -v base64 >/dev/null 2>&1; then
  _puddle_env_denied=' ${SHELL_DENYLIST} '
  declare -A _puddle_env_last=()

  _puddle_env_report() {
    local k v
    declare -A _puddle_now=()
    for k in \$(compgen -e); do
      case \$k in PUDDLE_*) continue ;; esac
      [[ \$_puddle_env_denied == *" \$k "* ]] && continue
      v=\${!k}
      (( \${#v} > ${MAX_VALUE_CHARS} )) && continue
      _puddle_now[\$k]=\$v
    done
    for k in "\${!_puddle_now[@]}"; do
      if [[ -z \${_puddle_env_last[\$k]+x} || \${_puddle_env_last[\$k]} != "\${_puddle_now[\$k]}" ]]; then
        printf '\\033]7733;set;%s;%s\\007' "\$(_puddle_env_b64 "\$k")" "\$(_puddle_env_b64 "\${_puddle_now[\$k]}")"
      fi
    done
    for k in "\${!_puddle_env_last[@]}"; do
      if [[ -z \${_puddle_now[\$k]+x} ]]; then
        printf '\\033]7733;unset;%s\\007' "\$(_puddle_env_b64 "\$k")"
      fi
    done
    _puddle_env_last=()
    for k in "\${!_puddle_now[@]}"; do _puddle_env_last[\$k]=\${_puddle_now[\$k]}; done
  }

  # Seed after ~/.bashrc: rc exports and re-injected vars are baseline.
  for _puddle_k in \$(compgen -e); do
    case \$_puddle_k in PUDDLE_*) continue ;; esac
    [[ \$_puddle_env_denied == *" \$_puddle_k "* ]] && continue
    _puddle_env_v=\${!_puddle_k}
    (( \${#_puddle_env_v} > ${MAX_VALUE_CHARS} )) && continue
    _puddle_env_last[\$_puddle_k]=\$_puddle_env_v
  done
  unset _puddle_k _puddle_env_v
fi

_puddle_prompt_report() {
  if [ -n "\$_puddle_session_history_file" ]; then
    # Append only this tab's new commands, then merge commands appended by
    # sibling tabs. Reclaim the private destination from any runtime hook that
    # repointed it; never rewrite the shared file or replace the live list.
    HISTFILE=\$_puddle_session_history_file
    history -a "\$_puddle_session_history_file" 2>/dev/null
    history -n "\$_puddle_session_history_file" 2>/dev/null
  fi
  _puddle_cwd_report
  _puddle_env_report
}
# Bash 5 prompt frameworks may use PROMPT_COMMAND as an array. Preserve that
# shape; older/scalar configurations retain their exact command string.
if [[ \$(declare -p PROMPT_COMMAND 2>/dev/null) == 'declare -a'* ]]; then
  PROMPT_COMMAND=(_puddle_prompt_report "\${PROMPT_COMMAND[@]}")
else
  PROMPT_COMMAND="_puddle_prompt_report\${PROMPT_COMMAND:+;\$PROMPT_COMMAND}"
fi
`;

